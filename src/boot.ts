// Generates the script and the systemd unit that restore sessions after a reboot.
// Pure logic (no vscode): tested with node --test.
import { shQuote, SavedSession } from './core';

export const UNIT_NAME = 'claude-tmux-restore';

/** Field separator: the ASCII "unit separator". Unlike a tab, bash does not treat it as whitespace, so an
 *  empty field (for example no remote name) is kept instead of shifting the columns. */
export const SEP = '\x1f';

/** One line per session: window SEP id SEP name SEP dir. Separators and newlines inside values become a space. */
export function toList(sessions: SavedSession[], fallbackDir: string): string {
  const clean = (v: string) => v.replace(/[\x1f\t\r\n]+/g, ' ');
  return sessions.map(s => [clean(s.window), clean(s.id), clean(s.name), clean(s.dir || fallbackDir)].join(SEP)).join('\n') + (sessions.length ? '\n' : '');
}

/** Format 2 adds the group as a 5th field. The v1 list (4 fields) is still written for scripts installed by older versions. */
export const RESTORE_FORMAT = 2;

export function toGroupList(sessions: SavedSession[], fallbackDir: string): string {
  const clean = (v: string) => v.replace(/[\x1f\t\r\n]+/g, ' ');
  return sessions.map(s => [clean(s.window), clean(s.id), clean(s.name), clean(s.dir || fallbackDir), clean(s.group || '')].join(SEP)).join('\n') + (sessions.length ? '\n' : '');
}

/** Format of an installed restore script, read from its header (1 if it has no marker). */
export function scriptFormat(text: string): number {
  const m = /^# restore-script-format: (\d+)/m.exec(text);
  return m ? +m[1] : 1;
}

export interface ScriptOpts { claudeBin: string; tmuxSession: string; listFile: string }

export function renderRestoreScript(o: ScriptOpts): string {
  return `#!/usr/bin/env bash
# Generated by the "tmux Session Keeper" extension. Edit sessions from the extension, not here.
# restore-script-format: ${RESTORE_FORMAT}
# Restores one tmux window per saved session, each in its group (a tmux session). Safe to run again:
# existing windows are left alone.
CLAUDE_BIN=${shQuote(o.claudeBin)}
TMUX_SESSION=${shQuote(o.tmuxSession)}
LIST=\${CLAUDE_TMUX_LIST:-${shQuote(o.listFile)}}

[ -r "$LIST" ] || { echo "restore-sessions: cannot read $LIST" >&2; exit 0; }
q() { printf "'%s'" "\${1//\\'/\\'\\\\\\'\\'}"; }

while IFS=$'\\037' read -r win id name dir group; do
  [ -z "$win" ] && continue
  grp="\${group:-$TMUX_SESSION}"
  [ -d "$dir" ] || { echo "restore-sessions: skipping '$win', directory '$dir' does not exist" >&2; continue; }
  cmd="$(q "$CLAUDE_BIN") --resume $(q "$id")"
  [ -n "$name" ] && cmd="$cmd --remote-control $(q "$name")"
  # "=" forces an exact match: without it tmux treats "claude" as a prefix of "claude-rc".
  if ! tmux has-session -t "=$grp" 2>/dev/null; then
    tmux new-session -d -s "$grp" -n "$win" -c "$dir" "$cmd"
  elif ! tmux list-windows -t "=$grp" -F '#W' | grep -qxF -- "$win"; then
    tmux new-window -t "=$grp:" -n "$win" -c "$dir" "$cmd"
  fi
done < "$LIST"
`;
}

/** Escapes a value for a systemd unit file: "%" is doubled and values with spaces are quoted. */
export function unitQuote(v: string): string {
  const e = v.replace(/%/g, '%%').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return /[\s"'\\]/.test(v) ? `"${e}"` : e;
}

export interface UnitOpts { scriptPath: string; pathDirs: string[] }

export function renderUnit(o: UnitOpts): string {
  const uniq = [...new Set(o.pathDirs.filter(Boolean))].join(':');
  return `[Unit]
Description=Restore Claude Code sessions in tmux

[Service]
Type=oneshot
RemainAfterExit=yes
KillMode=process
# The tmux server may be shared with other sessions. Without this, stopping the unit that happened to start it kills them all.
Environment=${unitQuote('PATH=' + uniq)}
ExecStart=${unitQuote(o.scriptPath)}

[Install]
WantedBy=default.target
`;
}

export interface ServerScriptOpts { claudeBin: string; name: string; dir: string; logDir: string; slug: string; autoUpdate: boolean }

/** Script que mantiene `claude remote-control` vivo: si el proceso termina (corte de red, etc.) lo relanza. */
export function renderServerScript(o: ServerScriptOpts): string {
  const update = o.autoUpdate ? '"$CLAUDE_BIN" update || true\n' : '';
  return `#!/usr/bin/env bash
# Generated by the "tmux Session Keeper" extension. Keeps \`claude remote-control\` running.
# If it exits (network loss, for example) it is started again after a short delay. Re-running it in the
# same directory makes Claude Code pick up the sessions it was serving instead of creating new ones.
CLAUDE_BIN=${shQuote(o.claudeBin)}
NAME=${shQuote(o.name)}
DIR=${shQuote(o.dir)}
LOG_DIR=${shQuote(o.logDir)}
SLUG=${shQuote(o.slug)}
DELAY=\${CLAUDE_TMUX_RESTART_DELAY:-15}

mkdir -p "$LOG_DIR"
cd "$DIR" || { echo "remote-control server: directory '$DIR' does not exist" >&2; exit 1; }
${update}while true; do
  "$CLAUDE_BIN" remote-control --name "$NAME" --verbose --debug-file "$LOG_DIR/$SLUG-debug.log"
  rc=$?
  echo "$(date '+%Y-%m-%d %H:%M:%S') remote-control exited (code $rc). Restarting in $DELAY s" >> "$LOG_DIR/$SLUG-restarts.log"
  sleep "$DELAY"
done
`;
}

export interface ServerUnitOpts { tmuxBin: string; session: string; scriptPath: string; pathDirs: string[]; slug: string }

export const serverUnitName = (slug: string) => `claude-rc-${slug}`;

export function renderServerUnit(o: ServerUnitOpts): string {
  const uniq = [...new Set(o.pathDirs.filter(Boolean))].join(':');
  return `[Unit]
Description=Claude Code Remote Control server (${o.slug}) in tmux

[Service]
Type=oneshot
RemainAfterExit=yes
KillMode=process
# The tmux server may be shared with other sessions. Without this, stopping the unit that happened to start it kills them all.
Environment=${unitQuote('PATH=' + uniq)}
ExecStart=${unitQuote(o.tmuxBin)} new-session -d -s ${unitQuote(o.session)} ${unitQuote(o.scriptPath)}
ExecStop=${unitQuote(o.tmuxBin)} kill-session -t ${unitQuote('=' + o.session)}

[Install]
WantedBy=default.target
`;
}
